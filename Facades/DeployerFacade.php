    protected function isCliError(string $cliOutput): bool {
        return mb_strpos($cliOutput, 'ERROR') !== false
            || mb_strpos($cliOutput, 'FAILED') !== false
            || mb_stripos($cliOutput, SelfUpdateInstaller::MESSAGE_INSTALLATION_FAILED)
            || mb_stripos($cliOutput, 'PHP Fatal error') // CLI errors - e.g. `PHP Fatal error:  Composer detected issues in your platform: ...`
        ;
    }
    
    /**
     * Looks for a pending deployment (in status 60) and returns the corresponding file for download
     * 
     * FIXME save the filename in the deployment data, so it does not need to be calculated
     * here and the recipies are free to use any filename they like
     * FIXME give hosts aliases too. UIDs for hosts are not really comfortable
     * 
     * @param string $projectAlias
     * @param string $hostName
     * @throws FileNotFoundError
     * @return ResponseInterface
     */
    protected function createResponseForOTA(string $projectAlias, string $hostName, bool $redeploy = false, string $nativeProtocol = '', bool $secureRequest = false) : ResponseInterface
    {
        $ds = $this->createDeploymentPublishedSheet($projectAlias, $hostName);
        $ds->getColumns()->addMultiple([
            'build__name',
            'host__name',
            'deploy_recipe_file',
            'status'
        ]);
        $ds->dataRead();
        
        $headers = $this->buildHeadersCommon();
        
        if ($ds->isEmpty()) {
            if ($redeploy === true) {
                try {
                    $this->redeploy($projectAlias, $hostName);
                    $ds = $this->createDeploymentPublishedSheet($projectAlias, $hostName);
                    $ds->getColumns()->addMultiple([
                        'build__name',
                        'host__name',
                        'deploy_recipe_file',
                        'status'
                    ]);
                    $ds->dataRead();
                } catch (\Throwable $e) {
                    return new Response(500, $headers, 'OTA redeployment failed: ' . $e->getMessage());
                }
            } else {
                return new Response(304, $headers, 'No updates found for project "' . $projectAlias . '"');
            }
        }
        
        // Generated by GitHub Copilot - Nov-05-2026
        if ($ds->isEmpty()) {
            return new Response(304, $headers, 'No published update is available.');
        }
        // Generated by GitHub Copilot - Nov-05-2026
        if (NativeOtaPackage::isManualPrototype((string) $ds->getCellValue('deploy_recipe_file', 0))) {
            return new Response(409, $headers, 'This deployment is manual transfer, not an OTA publication.');
        }
        if (NativeOtaPackage::isPrototype((string) $ds->getCellValue('deploy_recipe_file', 0))) {
            if (! $secureRequest) {
                return new Response(400, $headers, 'Native OTA downloads require HTTPS.');
            }
            if ($nativeProtocol !== '1') {
                return new Response(426, $headers, 'This deployment requires a native-OTA-capable SelfUpdate client.');
            }
            return $this->createResponseForNativeOTA($ds, $projectAlias, $headers);
        }
        $filename = $ds->getCellValue('build__name', 0) . '_' . Deploy::getHostAlias($ds->getCellValue('host__name', 0)) . '.phx';
        $path = $this->getWorkbench()->getInstallationPath() 
        . DIRECTORY_SEPARATOR . FilePathDataType::normalize($this->getApp()->getConfig()->getOption('PROJECTS_FOLDER_RELATIVE_TO_BASE'))
        . DIRECTORY_SEPARATOR . $projectAlias
        . DIRECTORY_SEPARATOR . 'builds'
        . DIRECTORY_SEPARATOR;
        
        if (! file_exists($path . $filename)) {
            throw new FileNotFoundError('Deployment file ' . $path . $filename . ' not found!');
        }

        $downloadMaxExecutionTime = (int) $this->getApp()->getConfig()->getOption('OTA_DOWNLOAD_MAX_EXECUTION_TIME');
        $currentMaxExecutionTime = (int) ini_get('max_execution_time');
        if ($currentMaxExecutionTime > 0 && $currentMaxExecutionTime < $downloadMaxExecutionTime) {
            set_time_limit($downloadMaxExecutionTime);
        }
        
        $headers = array_merge($headers, [
            'Expires' => 0,
            'Cache-Control', 'must-revalidate, post-check=0, pre-check=0',
            'Pragma' => 'public',
            'Content-Disposition' => 'attachment; filename=' . $filename,
            'Content-Type' => 'application/x-httpd-php'
        ]);
        
        $resource = fopen($path . $filename, 'r');
        $stream = Utils::streamFor($resource);
        
        $statusSheet = $ds->extractSystemColumns();
        $statusSheet->setCellValue('status', 0, 62);
        $statusSheet->dataUpdate();
        
        return new Response(200, $headers, $stream);
    }

