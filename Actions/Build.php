    protected function performDeferred(TaskInterface $task = null, DataSheetInterface $buildData = null) : \Generator
    {
        if ($task === null) {
            throw new InvalidArgumentException('Missing argument $task in deferred action call!');
        }
        
        if ($buildData === null) {
