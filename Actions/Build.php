                $msg = 'ERROR auditing ' . $buildName . ': ' . $e->getMessage() . PHP_EOL;
            }

            yield $msg;
            $log .= $msg;
            $buildData->setCellValue('log', 0, $log);
            $buildData->dataUpdate(false);
        }

