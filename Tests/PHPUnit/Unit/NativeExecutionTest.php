    /**
     * The Asset-Packagist workaround keeps existing repositories and prioritizes the
     * latest-cache endpoints for packages present in the previous lock.
     */
    public function testAssetPackagistFixUsesPreviousLock(): void
    {
        $composerJson = json_encode([
            'name' => 'example/build',
            'repositories' => [['type' => 'composer', 'url' => 'https://packages.example.org']]
        ], JSON_THROW_ON_ERROR);
        $composerLock = json_encode([
            'packages' => [
                ['name' => 'npm-asset/scope--package'],
                ['name' => 'bower-asset/jquery'],
                ['name' => 'vendor/ordinary']
            ]
        ], JSON_THROW_ON_ERROR);

        $result = json_decode(AssetPackagistFix::apply($composerJson, $composerLock), true, 512, JSON_THROW_ON_ERROR);
        self::assertSame([
            'type' => 'composer',
            'url' => 'https://cdn.asset-packagist.org/p/npm-asset/scope--package/latest.json',
            'only' => ['npm-asset/scope--package']
        ], $result['repositories'][0]);
        self::assertSame([
            'type' => 'composer',
            'url' => 'https://cdn.asset-packagist.org/p/bower-asset/jquery/latest.json',
            'only' => ['bower-asset/jquery']
        ], $result['repositories'][1]);
        self::assertSame('https://packages.example.org', $result['repositories'][2]['url']);
    }

    /**
     * The Composer build executor runs with argument-vector processes and packages the
     * generated lockfile and PackageManager hooks without a Deployer runtime.
     */
    public function testComposerBuildCreatesArchiveAndLockfile(): void
    {
        $workspace = $this->createTemporaryDirectory('native-build-');
        $composerScript = <<<'PHP'
<?php
// Generated by GitHub Copilot - Oct-30-2026
$workspace = getcwd();
mkdir($workspace . DIRECTORY_SEPARATOR . 'vendor');
file_put_contents($workspace . DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR . 'autoload.php', "<?php\n");
file_put_contents($workspace . DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR . 'licenses.json', '{"packages":[]}');
file_put_contents($workspace . DIRECTORY_SEPARATOR . 'composer.lock', '{"packages":[]}');
PHP;
        file_put_contents($workspace . DIRECTORY_SEPARATOR . 'composer.phar', $composerScript);
        file_put_contents($workspace . DIRECTORY_SEPARATOR . 'composer.json', '{"name":"example/build","require":{}}');
        $archivePath = $workspace . DIRECTORY_SEPARATOR . 'builds' . DIRECTORY_SEPARATOR . 'build.tar.gz';

        try {
            $executor = new ComposerBuildExecutor();
            $run = $executor->execute(
                $workspace,
                $archivePath,
                PHP_BINARY,
                $workspace . DIRECTORY_SEPARATOR . '.composer',
                60,
                ['vendor', 'composer.json', 'composer.lock', 'composer.phar']
            );
            foreach ($run as $_output) {
            }
            $result = $run->getReturn();

            self::assertSame('{"packages":[]}', $result['composer_lock']);
            self::assertFileExists($archivePath);
            self::assertSame("\x1f\x8b", file_get_contents($archivePath, false, null, 0, 2));
            self::assertSame('{"packages":[]}', $result['package_bom']);

            $archive = new \PharData($archivePath);
            $archivedComposerJson = json_decode($archive['composer.json']->getContent(), true, 512, JSON_THROW_ON_ERROR);
            self::assertSame(
                'axenox\\PackageManager\\StaticInstaller::composerFinishInstall',
                $archivedComposerJson['scripts']['post-install-cmd'][0]
            );
            self::assertSame("<?php\n", $archive['vendor/autoload.php']->getContent());
        } finally {
            $this->removeDirectory($workspace);
        }
    }

    /**
     * A real Composer install can be exercised offline when a Composer PHAR is supplied
     * by the test environment.
     */
    public function testRealComposerInstallWithoutDeployerWhenComposerPharIsAvailable(): void
    {
        $composerPhar = getenv('COMPOSER_PHAR');
        if (! is_string($composerPhar) || ! is_file($composerPhar)) {
            self::markTestSkipped('Set COMPOSER_PHAR to run the real Composer integration check.');
        }
        $workspace = $this->createTemporaryDirectory('composer-install-');
        copy($composerPhar, $workspace . DIRECTORY_SEPARATOR . 'composer.phar');
        file_put_contents($workspace . DIRECTORY_SEPARATOR . 'composer.json', '{"name":"example/offline-build","require":{}}');
        $archivePath = $workspace . DIRECTORY_SEPARATOR . 'builds' . DIRECTORY_SEPARATOR . 'offline.tar.gz';

        try {
            $executor = new ComposerBuildExecutor();
            $run = $executor->execute(
                $workspace,
                $archivePath,
                PHP_BINARY,
                $workspace . DIRECTORY_SEPARATOR . '.composer',
                120,
                ['vendor', 'composer.json', 'composer.lock', 'composer.phar']
            );
            foreach ($run as $_output) {
            }
            $result = $run->getReturn();

            self::assertNotEmpty($result['composer_lock']);
            self::assertNull($result['package_bom']);
            self::assertFileExists($workspace . DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR . 'autoload.php');
            self::assertFileExists($archivePath);
            self::assertStringNotContainsString('deployer/deployer', $result['composer_lock']);
        } finally {
            $this->removeDirectory($workspace);
        }
    }

    /**
     * The self-extractor safely quotes configuration values and appends the archive bytes.
     */
    public function testDeploymentPackageBuilderQuotesConfigurationAndAppendsArchive(): void
    {
        $workspace = $this->createTemporaryDirectory('native-deploy-');
        $template = dirname(__DIR__, 3) . '/Recipes/SelfExtractingPHP/SelfExtractingDeployment.php';
        $archivePath = $workspace . DIRECTORY_SEPARATOR . 'release.tar.gz';
        $outputPath = $workspace . DIRECTORY_SEPARATOR . 'release_host.phx';
        $archiveContents = "archive contents";
        file_put_contents($archivePath, $archiveContents);

        try {
            (new DeploymentPackageBuilder())->build(
                $template,
                $archivePath,
                $outputPath,
                [
                    'basic_deploy_path' => "C:\\deployment\\client' ; exit();",
                    'relative_deploy_path' => 'releases',
                    'shared_dirs' => ['data', 'logs'],
                    'copy_dirs' => ['config'],
                    'keep_releases' => 4,
                    'deploy_config' => ['local_vendors' => []],
                    'php_path' => 'php'
                ]
            );

            $artifact = file_get_contents($outputPath);
            self::assertNotFalse($artifact);
            self::assertStringContainsString(var_export("C:\\deployment\\client' ; exit();", true), $artifact);
            self::assertSame($archiveContents, substr($artifact, -strlen($archiveContents)));
            $lint = new \Symfony\Component\Process\Process([PHP_BINARY, '-l', $outputPath]);
            $lint->mustRun();
            self::assertTrue($lint->isSuccessful(), $lint->getOutput());
        } finally {
            $this->removeDirectory($workspace);
        }
    }

