    /**
     * Updater push uses the configured endpoint, authenticated multipart upload and TLS verification.
     */
    public function testUpdaterPushUploadsArtifactAndReportsSuccess(): void
    {
        $workspace = $this->createTemporaryDirectory('native-push-');
        $archivePath = $workspace . DIRECTORY_SEPARATOR . 'release.tar.gz';
        $template = dirname(__DIR__, 3) . '/Recipes/SelfExtractingPHP/SelfExtractingDeployment.php';
        file_put_contents($archivePath, 'build archive');
        $history = [];
        $stack = HandlerStack::create(new MockHandler([new Response(201, [], 'queued')]));
        $stack->push(Middleware::history($history));
        $client = new Client(['handler' => $stack]);

        try {
            $executor = new LegacyDeploymentExecutor(null, $client);
            $execution = $executor->execute(
                'LocalBldUpdaterPush',
                '1.2.3+20261030120000',
                'test_host',
                $archivePath,
                $workspace,
                $template,
                [
                    'basic_deploy_path' => 'C:\\deployment',
                    'relative_deploy_path' => 'site',
                    'php_path' => 'php'
                ],
                [],
                [
                    'url' => 'https://updates.example.org/api',
                    'user' => 'updater',
                    'password' => 'test-secret'
                ]
            );
            $output = '';
            foreach ($execution as $message) {
                $output .= $message;
            }
            $result = $execution->getReturn();

            self::assertFalse($result['published']);
            self::assertSame(
                $workspace . DIRECTORY_SEPARATOR . '1.2.3+20261030120000_test_host.phx',
                $result['artifact_path']
            );
            self::assertSame('POST', $history[0]['request']->getMethod());
            self::assertSame('https://updates.example.org/api', (string) $history[0]['request']->getUri());
            self::assertTrue($history[0]['options']['verify']);
            self::assertSame(['updater', 'test-secret'], $history[0]['options']['auth']);
            self::assertStringContainsString('HTTP 201', $output);
            self::assertStringContainsString('queued', $output);
        } finally {
            $this->removeDirectory($workspace);
        }
    }

