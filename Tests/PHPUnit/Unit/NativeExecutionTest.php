    /**
     * Creates an isolated directory for a test case.
     *
     * @param string $prefix
     * @return string
     */
    private function createTemporaryDirectory(string $prefix): string
    {
        $directory = sys_get_temp_dir() . DIRECTORY_SEPARATOR . uniqid($prefix, true);
        if (! mkdir($directory, 0777, true) && ! is_dir($directory)) {
            throw new RuntimeException('Cannot create temporary test directory.');
        }
        return $directory;
    }

    /**
     * Removes only the test directory created by this test class.
     *
     * @param string $directory
     */
    private function removeDirectory(string $directory): void
    {
        if (! is_dir($directory)) {
            return;
        }
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST
        );
        foreach ($iterator as $item) {
            $item->isDir() ? rmdir($item->getPathname()) : unlink($item->getPathname());
        }
        rmdir($directory);
    }
