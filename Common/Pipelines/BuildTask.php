<?php
namespace axenox\Deployer\Common\Pipelines;

use axenox\Deployer\Interfaces\Pipelines\BuildTaskInterface;

/**
 * Action-resolved inputs for one isolated native build.
 *
 * @author Brooklyn Fränzschky
 */
final class BuildTask implements BuildTaskInterface
{
    /**
     * Keeps runtime paths and overrides separate from prototype UXON.
     *
     * @param string $projectPath
     * @param string $archiveDirectory
     * @param string $buildName
     * @param string $phpExecutable
     * @param string $composerPhar
     * @param string|null $composerJson Complete per-run replacement, if supplied.
     * @param string $composerAuth Global authentication defaults.
     * @param string|null $licensesJson
     * @param string|null $comment
     * @param string|null $notes
     * @param string|null $previousComposerLock Previous successful build of this variant only.
     */
    public function __construct(
        public string $projectPath,
        public string $archiveDirectory,
        public string $buildName,
        public string $phpExecutable,
        public string $composerPhar,
        public ?string $composerJson = null,
        public string $composerAuth = '{}',
        public ?string $licensesJson = null,
        private ?string $comment = null,
        private ?string $notes = null,
        // Generated by GitHub Copilot - Nov-05-2026
        public ?string $previousComposerLock = null
    ) {
    }

    /**
     * @return string|null
     */
    public function getComment(): ?string
    {
        return $this->comment;
    }

    /**
     * @return string|null
     */
    public function getNotes(): ?string
    {
        return $this->notes;
    }
}
